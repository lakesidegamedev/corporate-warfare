#!/usr/bin/env python3
"""Write content/geography/states.json: the playable Great Lakes and Ohio Valley states.

Populations are the Census 2000 counts. GDP, average pay and union density are rounded public
circa-2000 figures, used only as relative indices. State condition indices are authored game
estimates. Freight lane distances are great-circle distances between hub cities times a 1.25
road factor.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# code, name, hub city, lat, lon, Census 2000 population, GDP $bn (rounded),
# average annual pay $ (rounded), union membership % (rounded)
STATES = [
    ("IL", "Illinois", "Chicago", 41.878, -87.630, 12_419_293, 470, 39_000, 19.0),
    ("IN", "Indiana", "Indianapolis", 39.768, -86.158, 6_080_485, 190, 30_000, 14.0),
    ("KY", "Kentucky", "Louisville", 38.253, -85.759, 4_041_769, 115, 28_000, 10.5),
    ("MI", "Michigan", "Detroit", 42.331, -83.046, 9_938_444, 335, 38_000, 21.0),
    ("NY", "New York", "New York City", 40.713, -74.006, 18_976_457, 770, 46_500, 25.5),
    ("OH", "Ohio", "Columbus", 39.961, -82.999, 11_353_140, 380, 32_500, 17.5),
    ("PA", "Pennsylvania", "Harrisburg", 40.274, -76.884, 12_281_054, 390, 34_000, 15.5),
    ("WV", "West Virginia", "Charleston", 38.350, -81.633, 1_808_344, 42, 26_000, 14.5),
]

# Authored condition indices, 0..10000 (10000 best, except crime and cost of living where 10000
# is the corridor average): power grid reliability, road condition, broadband reach (2000 era),
# workforce skill, crime, cost of living, land cost.
CONDITIONS = {
    "IL": (9600, 6200, 2600, 6200, 11500, 11000, 12000),
    "IN": (9700, 6800, 1800, 5000, 8500, 8800, 8500),
    "KY": (9500, 6000, 1400, 4400, 8000, 8500, 8000),
    "MI": (9500, 5200, 2200, 5600, 11000, 9800, 10000),
    "NY": (9400, 5000, 3200, 6800, 10500, 15000, 16000),
    "OH": (9700, 6400, 2000, 5400, 9500, 9300, 9500),
    "PA": (9600, 5600, 2200, 5700, 9000, 10000, 10000),
    "WV": (9300, 4800, 1000, 4000, 7500, 8000, 7000),
}

ROAD_FACTOR = 1.25


def great_circle_km(a, b):
    lat1, lon1, lat2, lon2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lon2 - lon1) / 2) ** 2
    return 6371.0 * 2 * math.asin(math.sqrt(h))


def main():
    base_gdp = 380  # Ohio = 10000
    base_pay = 34_000
    regions = []
    for code, name, city, lat, lon, population, gdp, pay, union in STATES:
        grid, road, broadband, skill, crime, living, land = CONDITIONS[code]
        regions.append({
            "code": code,
            "name": name,
            "states": [code],
            "principal_city": f"{city}, {code}",
            "lat_milli": round(lat * 1000),
            "lon_milli": round(lon * 1000),
            "population_2000": population,
            "wage_index_bps": round(pay * 10_000 / base_pay),
            "demand_index_bps": round(gdp * 10_000 / base_gdp),
            "land_index_bps": land,
            "opening_organisation_bps": round(union * 100),
            "conditions": {
                "power_grid_bps": grid,
                "road_bps": road,
                "broadband_bps": broadband,
                "skill_bps": skill,
                "crime_bps": crime,
                "cost_of_living_bps": living,
            },
        })
    lanes = []
    for i, a in enumerate(STATES):
        for b in STATES[i + 1:]:
            km = great_circle_km((a[3], a[4]), (b[3], b[4])) * ROAD_FACTOR
            lanes.append({"a": a[0], "b": b[0], "km": round(km)})
    document = {
        "schema": 2,
        "classification": "playable states of the Great Lakes and Ohio Valley; Census 2000 populations, rounded public circa-2000 GDP, pay and union figures as relative indices, authored condition indices",
        "vintage": "nominal January 2000 start",
        "official_source": "US Census Bureau 2000 decennial counts; BEA, BLS and union membership figures rounded for indices",
        "attempts": [],
        "membership_status": "each playable region is one whole state; county shapes on the map are drawn from Census cartographic boundaries",
        "notes": "Generated by tools/map/build_states.py. Condition indices and calibrated demand are game estimates, not observations.",
        "regions": regions,
        "lanes": lanes,
    }
    out = ROOT / "content/geography/states.json"
    out.write_text(json.dumps(document, indent=2) + "\n")
    print(f"wrote {out} with {len(regions)} states and {len(lanes)} lanes")


if __name__ == "__main__":
    main()
