#!/usr/bin/env python3
"""Export the map's voxel models as true 3D data for the apps to draw from any angle.

The buildings, city blocks and countryside props come from tools/voxel_sprites.py and the
vehicles from tools/voxel_vehicles.py; this writes them as boxes, neighbouring voxels of one
colour merged greedily, so each model is a few dozen boxes the apps project through the map's
camera every frame. Turn the map and you see every side.

Axes: x east, y north, z up, in voxels, with the model centred on its footprint at the origin.
Buildings face south (their doors and signs on the low-y side, towards the default camera).
Vehicles point east (+x), centred on their length.

    python3 tools/voxel_models.py      writes apple/Resources/voxel-models.json
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "apple" / "Resources" / "voxel-models.json"


def load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / "tools" / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def hexcolour(c) -> str:
    return "#%02X%02X%02X" % tuple(c) if not isinstance(c, str) else c


def greedy(voxels: dict) -> list:
    """Merge voxels of one colour into boxes: grow along x, then y, then z."""
    left = dict(voxels)
    boxes = []
    for key in sorted(voxels, key=lambda k: (k[2], k[1], k[0])):
        if key not in left:
            continue
        colour = left[key]
        x0, y0, z0 = key
        x1 = x0 + 1
        while left.get((x1, y0, z0)) == colour:
            x1 += 1
        y1 = y0 + 1
        while all(left.get((x, y1, z0)) == colour for x in range(x0, x1)):
            y1 += 1
        z1 = z0 + 1
        while all(left.get((x, y, z1)) == colour for x in range(x0, x1) for y in range(y0, y1)):
            z1 += 1
        for x in range(x0, x1):
            for y in range(y0, y1):
                for z in range(z0, z1):
                    del left[(x, y, z)]
        boxes.append((x0, y0, z0, x1, y1, z1, colour))
    return boxes


def export(voxels: dict, face_south: bool) -> dict:
    xs = [k[0] for k in voxels]
    ys = [k[1] for k in voxels]
    x0, x1, y0, y1 = min(xs), max(xs) + 1, min(ys), max(ys) + 1
    if face_south:
        # The sprite models keep their fronts on the high-y side; turn them to face south.
        voxels = {(x, y1 - 1 - (y - y0), z): c for (x, y, z), c in voxels.items()}
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    boxes = greedy({k: hexcolour(c) for k, c in voxels.items()})
    return {
        "w": x1 - x0, "d": y1 - y0, "h": max(k[2] for k in voxels) + 1,
        "boxes": [[round(b[0] - cx, 1), round(b[1] - cy, 1), b[2], round(b[3] - cx, 1), round(b[4] - cy, 1), b[5], b[6]] for b in boxes],
    }


def main() -> None:
    sprites = load("voxel_sprites")
    vehicles = load("voxel_vehicles")
    models = {}
    for name, make in sprites.MODELS.items():
        for size in range(3):
            models[f"{name}/{size}"] = export(make(size).v, face_south=True)
    for name, make in sprites.CITY_KINDS.items():
        for size in range(3):
            models[f"{name}/{size}"] = export(make(size).v, face_south=True)
    for name, make in vehicles.MODELS.items():
        for livery, mine in (("neutral", False), ("player", True)):
            models[f"{name}/{livery}"] = export(make(mine).v, face_south=False)
    data = {
        "note": "Voxel models as boxes [x0, y0, z0, x1, y1, z1, colour]; x east, y north, z up, in voxels, centred on the "
                "footprint. Buildings face south; vehicles point east. Generated by tools/voxel_models.py.",
        "models": models,
    }
    OUT.write_text(json.dumps(data, separators=(",", ":")) + "\n")
    count = sum(len(m["boxes"]) for m in models.values())
    print(f"{len(models)} models, {count} boxes, {OUT.stat().st_size // 1024} KiB -> {OUT}")


if __name__ == "__main__":
    main()
